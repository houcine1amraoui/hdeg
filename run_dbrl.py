# Main
# ---------------------------------------------------------------------

def main() -> None:
    # 1. Load config
    with open("configs/config.yaml") as f:
        config = yaml.safe_load(f)
        
    set_seed(config["seed"])

    device = get_device()

    # # parse CLI args
    parser = argparse.ArgumentParser()
    parser.add_argument("--project_root_dir", type=str)
    args = parser.parse_args()

    # override project_root_directory
    if args.project_root_dir:
        config["project_root_dir"] = args.project_root_dir

    root = config["project_root_dir"]
    print(root)

    processed_data_folder = get_processed_folder(config)
    windows_dir = processed_data_folder

    output_dir = f"{processed_data_folder}/dbrl"
    output_path = f"{output_dir}/train_dbrl.pt"

    # -------------------------------------------------------------
    # Load prepared windows
    # -------------------------------------------------------------

    artifact = load_window_artifact(
        windows_dir=windows_dir,
        split="train",
    )

    (
        num_samples,
        window_size,
        num_devices,
    ) = validate_window_artifact(
        artifact
    )

    X = artifact["X"]

    print("Prepared window artifact")
    print(
        f"  X shape          : {X.shape}"
    )

    print(
        f"  y shape          : "
        f"{artifact['y'].shape}"
    )

    print(
        f"  window size      : {window_size}"
    )

    print(
        f"  number of devices: {num_devices}"
    )

    print(
        f"  number of samples: {num_samples}"
    )

    print()

    # -------------------------------------------------------------
    # Convert only X to a torch tensor.
    #
    # y remains in the artifact and is intentionally not passed to
    # DBRL during this standalone forward test.
    # -------------------------------------------------------------

    X_tensor = torch.from_numpy(
        X
    ).float()

    # -------------------------------------------------------------
    # DataLoader
    #
    # shuffle=False is intentional:
    #
    # sample i in the saved representation corresponds exactly to
    # sample i in the prepared window artifact.
    # -------------------------------------------------------------

    dataset = TensorDataset(
        X_tensor,
        torch.zeros(
            X_tensor.size(0),
            dtype=torch.float32,
        ),
    )

    dataloader = DataLoader(
        dataset,
        batch_size=config["hdeg"]["dbrl"]["batch_size"],
        shuffle=False,
        drop_last=False,
    )

    # -------------------------------------------------------------
    # Build DBRL
    # -------------------------------------------------------------

    model = build_dbrl(
        hidden_dim=config["hdeg"]["dbrl"]["hidden_dim"],
        embedding_dim=config["hdeg"]["dbrl"]["embedding_dim"],
        gru_layers=config["hdeg"]["dbrl"]["gru_layers"],
        graph_top_k=config["hdeg"]["dbrl"]["graph_top_k"],
        graph_self_loops=config["hdeg"]["dbrl"]["graph_self_loops"],
        graph_symmetric=config["hdeg"]["dbrl"]["graph_symmetric"],
        graph_heads=config["hdeg"]["dbrl"]["graph_heads"],
        num_devices=num_devices,
    )

    model = model.to(device)

    print("DBRL configuration")
    print(
        f"  hidden_dim       : {config['hdeg']['dbrl']['hidden_dim']}"
    )

    print(
        f"  embedding_dim    : {config['hdeg']['dbrl']['embedding_dim']}"
    )

    print(
        f"  GRU layers       : {config['hdeg']['dbrl']['gru_layers']}"
    )

    print(
        f"  graph_top_k      : {config['hdeg']['dbrl']['graph_top_k']}"
    )

    print(
        f"  graph_self_loops : "
        f"{config['hdeg']['dbrl']['graph_self_loops']}"
    )

    print(
        f"  graph_symmetric  : "
        f"{config['hdeg']['dbrl']['graph_symmetric']}"
    )

    print(
        f"  graph_heads      : {config['hdeg']['dbrl']['graph_heads']}"
    )

    print()

    # -------------------------------------------------------------
    # Run DBRL
    # -------------------------------------------------------------

    print("Running DBRL...")
    print()

    Z = run_dbrl(
        model=model,
        dataloader=dataloader,
        device=device,
        embedding_dim=config["hdeg"]["dbrl"]["embedding_dim"],
        num_devices=num_devices,
        max_batches=config["hdeg"]["dbrl"]["max_batches"],
    )

    # -------------------------------------------------------------
    # Final validation
    # -------------------------------------------------------------

    expected_samples = num_samples

    if (
        config["hdeg"]["dbrl"]["max_batches"] is not None
    ):
        expected_samples = min(
            num_samples,
            config["hdeg"]["dbrl"]["max_batches"] * config["hdeg"]["dbrl"]["batch_size"],
        )

    expected_shape = (
        expected_samples,
        num_devices,
        config["hdeg"]["dbrl"]["embedding_dim"],
    )

    if Z.shape != expected_shape:
        raise RuntimeError(
            "Final DBRL representation shape mismatch. "
            f"Expected {expected_shape}, "
            f"received {tuple(Z.shape)}."
        )

    if not torch.isfinite(Z).all():
        raise RuntimeError(
            "Final DBRL representations contain "
            "NaN or infinite values."
        )

    # -------------------------------------------------------------
    # Statistics
    # -------------------------------------------------------------

    print()
    print("=" * 70)
    print("DBRL forward pass completed")
    print("=" * 70)

    print(
        f"Z shape : {tuple(Z.shape)}"
    )

    print(
        f"Z dtype : {Z.dtype}"
    )

    print(
        f"Z min   : {Z.min().item():.6f}"
    )

    print(
        f"Z max   : {Z.max().item():.6f}"
    )

    print(
        f"Z mean  : {Z.mean().item():.6f}"
    )

    print(
        f"Z std   : {Z.std().item():.6f}"
    )

    print()

    print(
        "[PASS] DBRL input/output shape contract verified."
    )

    print(
        "[PASS] DBRL output contains only finite values."
    )

    # -------------------------------------------------------------
    # Save representations
    # -------------------------------------------------------------

    save_representations(
        output_path=output_path,
        representations=Z,
        split="train",
        window_size=window_size,
        num_devices=num_devices,
        embedding_dim=config["hdeg"]["dbrl"]["embedding_dim"],
        batch_size=config["hdeg"]["dbrl"]["batch_size"],
        seed=config["hdeg"]["dbrl"]["seed"],
        overwrite=config["hdeg"]["dbrl"]["overwrite"],
    )

    print()
    print(
        f"Representations saved to:\n"
        f"  {output_path}"
    )

    print()
    print("=" * 70)
    print("DBRL standalone test finished successfully.")
    print("=" * 70)


if __name__ == "__main__":
    main()